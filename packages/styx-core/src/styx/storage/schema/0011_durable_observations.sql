CREATE OR REPLACE FUNCTION styx_immutable_observation_presentation()
RETURNS trigger AS $$
BEGIN
    IF NEW.snapshot_token IS DISTINCT FROM OLD.snapshot_token OR
       NEW.consequence_id IS DISTINCT FROM OLD.consequence_id OR
       NEW.agent_id IS DISTINCT FROM OLD.agent_id OR
       NEW.lease_expires_at IS DISTINCT FROM OLD.lease_expires_at OR
       NEW.presented_at IS DISTINCT FROM OLD.presented_at OR
       NEW.presented_payload IS DISTINCT FROM OLD.presented_payload OR
       NEW.payload_hash IS DISTINCT FROM OLD.payload_hash OR
       NEW.presentation_version IS DISTINCT FROM OLD.presentation_version
    THEN
        RAISE EXCEPTION 'observation presentation is immutable'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS cognitive_presentations_immutable
    ON cognitive_presentations;
CREATE TRIGGER cognitive_presentations_immutable
BEFORE UPDATE ON cognitive_presentations
FOR EACH ROW EXECUTE FUNCTION styx_immutable_observation_presentation();
