    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'cognitive_observations_action_act_fk'
          AND conrelid = 'cognitive_consequences'::regclass
    ) THEN
        ALTER TABLE cognitive_consequences
            ADD CONSTRAINT cognitive_observations_action_act_fk
            FOREIGN KEY (action_act_id, agent_id)
            REFERENCES cognitive_acts(id, agent_id)
            DEFERRABLE INITIALLY DEFERRED;
    END IF;
