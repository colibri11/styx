-- Wave 39: evolve the existing consequence inbox into a durable observation
-- channel.  Legacy act-emitted consequences retain their physical rows and
-- nullable provenance.  Canonical observations are externally reduced,
-- immutable evidence and never become subjective memories on ingestion.

